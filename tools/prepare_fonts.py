#!/usr/bin/env python3
"""Prepares the fonts (already run once; the outputs are committed — rerun only to regenerate).

1) Extracts the glyphs needed for English + Turkish from u8g2's BDF fonts
   -> generator/fonts/*.bdf
2) Builds Adafruit GFX font headers for the screen the ESP32 draws itself (the live clock)
   -> firmware/ESP_Buddy/font_text.h   (6x10, ASCII + Turkish letters)
   -> firmware/ESP_Buddy/font_clock.h  (spleen 16x32, digits and ':')

Usage: python tools/prepare_fonts.py <u8g2>/tools/font/bdf
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

FONTS = ["4x6", "5x8", "6x10", "6x13B", "7x14B", "10x20",
         "helvB10", "helvB12", "helvB14", "helvB18", "helvB24", "spleen-16x32"]

EXTRA = [0x2022, 0x2026, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x20BA,
         0x25B2, 0x25BC, 0x2191, 0x2193, 0x2192, 0x2190]
CHARSET = set(range(32, 127)) | set(range(160, 384)) | set(EXTRA)

# Extra characters in the device font, after ASCII (codes start at 0x7F).
# Must be in the SAME order as TEXT_EXTRA in firmware/ESP_Buddy/ESP_Buddy.ino.
DEVICE_EXTRA = "ÇçĞğİıÖöŞşÜü°·"


def read_bdf(path):
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    head, glyphs, i = [], [], 0
    while i < len(lines) and not lines[i].startswith("STARTCHAR"):
        head.append(lines[i]); i += 1
    while i < len(lines):
        if lines[i].startswith("STARTCHAR"):
            block = []
            while not lines[i].startswith("ENDCHAR"):
                block.append(lines[i]); i += 1
            block.append("ENDCHAR")
            glyphs.append(block)
        i += 1
    return head, glyphs


def encoding(block):
    for s in block:
        if s.startswith("ENCODING"):
            return int(s.split()[1])
    return -1


def subset(src, dst):
    head, gl = read_bdf(src)
    gl = [g for g in gl if encoding(g) in CHARSET]
    head = [s for s in head if not s.startswith("CHARS ")]
    with open(dst, "w", encoding="latin-1") as f:
        f.write("\n".join(head + [f"CHARS {len(gl)}"]) + "\n")
        for g in gl:
            f.write("\n".join(g) + "\n")
        f.write("ENDFONT\n")
    return len(gl)


def parse_glyph(block):
    d = {"code": encoding(block)}
    rows, inside = [], False
    for s in block:
        p = s.split()
        if p[0] == "DWIDTH":
            d["adv"] = int(p[1])
        elif p[0] == "BBX":
            d["w"], d["h"], d["xo"], d["yo"] = map(int, p[1:5])
        elif p[0] == "BITMAP":
            inside = True
        elif p[0] == "ENDCHAR":
            inside = False
        elif inside:
            rows.append(int(s, 16) if s else 0)
    d["rows"] = rows
    d["row_bytes"] = (d["w"] + 7) // 8
    return d


def gfx_header(src, name, chars):
    _, gl = read_bdf(src)
    table = {encoding(g): parse_glyph(g) for g in gl}
    asc = desc = 0
    with open(src, encoding="latin-1") as f:
        for s in f:
            if s.startswith("FONT_ASCENT"): asc = int(s.split()[1])
            if s.startswith("FONT_DESCENT"): desc = int(s.split()[1])
    bitmap, glyphs = [], []
    for cp in chars:
        g = table.get(cp) or table[ord("?")]
        bits = []
        for r in g["rows"]:
            for x in range(g["w"]):
                bits.append((r >> (g["row_bytes"] * 8 - 1 - x)) & 1)
        ofs = len(bitmap)
        for i in range(0, len(bits), 8):
            b = 0
            for j, v in enumerate(bits[i:i + 8]):
                b |= v << (7 - j)
            bitmap.append(b)
        glyphs.append((ofs, g["w"], g["h"], g["adv"], g["xo"], -(g["yo"] + g["h"])))
    s = [f"// Generated by tools/prepare_fonts.py from {os.path.basename(src)} — do not edit", "#pragma once",
         "#include <Adafruit_GFX.h>", f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
    for i in range(0, len(bitmap), 16):
        s.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
    s.append("};")
    s.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for g in glyphs:
        s.append("  {%d, %d, %d, %d, %d, %d}," % g)
    s.append("};")
    s.append(f"const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, 0x20, 0x{0x20 + len(chars) - 1:02X}, {asc + desc}}};")
    return "\n".join(s) + "\n"


def main():
    src = sys.argv[1]
    for f in FONTS:
        n = subset(os.path.join(src, f + ".bdf"), os.path.join(ROOT, "generator", "fonts", f + ".bdf"))
        print(f, n, "glyphs")
    fw = os.path.join(ROOT, "firmware", "ESP_Buddy")
    text = list(range(0x20, 0x7F)) + [ord(c) for c in DEVICE_EXTRA]
    with open(os.path.join(fw, "font_text.h"), "w", encoding="utf-8") as f:
        f.write(gfx_header(os.path.join(src, "6x10.bdf"), "FontText", text))
    with open(os.path.join(fw, "font_clock.h"), "w", encoding="utf-8") as f:
        f.write(gfx_header(os.path.join(src, "spleen-16x32.bdf"), "FontClock", list(range(0x20, 0x3B))))
    print("GFX headers written")


if __name__ == "__main__":
    main()
